import Foundation
import SwiftUI
import Testing
@testable import Fur_Affinity

struct AnimatedImageDecodeTests {
    @Test
    func aGIFKeepsItsBytes() throws {
        let gif = try #require(Data(base64Encoded: animatedAvatarBase64, options: .ignoreUnknownCharacters))
        #expect(animatedImageData(decoding: gif) == gif)
    }

    @Test
    func aStillImageKeepsNothing() throws {
        let gif = try #require(Data(base64Encoded: animatedAvatarBase64, options: .ignoreUnknownCharacters))
        let png = try #require(UIImage(data: gif)?.pngData())
        #expect(animatedImageData(decoding: png) == nil)
    }
}

