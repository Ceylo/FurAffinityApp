//  What Kingfisher's decode keeps for `KFAnimatedImage` to play — on iOS only, so this
//  checks upstream's path, not the fork's Android one: that decode builds a Bitmap-backed
//  `UIImage`, which needs a JVM, and a native test executable has none
//  (Android/docs/build-and-run.md § Test).
